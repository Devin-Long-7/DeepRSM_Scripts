#!/usr/bin/env python3
"""Create one CMAQ EmissCtrl namelist for a regional NOx scan.

The file is copied from the validated baseline namelist and receives one
additional ``m`` rule in the EmissionScalingRules section.  ``m`` multiplies
the existing gridded-emission mapping in the selected CMAQ region; it does
not alter VOC, SO2, NH3, biogenic, or boundary-condition inputs.
"""

from __future__ import annotations

import argparse
import math
import re
from pathlib import Path


ALLOWED_SCOPES = {
    "GZ",
    "SZ",
    "FS",
    "DG",
    "HZ",
    "JM",
    "ZH",
    "ZQ",
    "ZS",
    "GD-PRD",  # non-nine-city Guangdong mask
    "D3-PRD",  # full-D3 complement of the nine PRD cities
    "EVERYWHERE",
}

REGION_LINES = """   'GZ'      ,'CMAQ_MASKS' ,'GZ',
   'SZ'      ,'CMAQ_MASKS' ,'SZ',
   'FS'      ,'CMAQ_MASKS' ,'FS',
   'DG'      ,'CMAQ_MASKS' ,'DG',
   'HZ'      ,'CMAQ_MASKS' ,'HZ',
   'JM'      ,'CMAQ_MASKS' ,'JM',
   'ZH'      ,'CMAQ_MASKS' ,'ZH',
   'ZQ'      ,'CMAQ_MASKS' ,'ZQ',
   'ZS'      ,'CMAQ_MASKS' ,'ZS',
   'GD-PRD'  ,'CMAQ_MASKS' ,'GD-PRD',
   'D3-PRD'  ,'CMAQ_MASKS' ,'D3-PRD',
"""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--scope", required=True)
    parser.add_argument("--nox-factor", required=True, type=float)
    return parser.parse_args()


def format_factor(value: float) -> str:
    """Use a Fortran-friendly decimal without losing useful precision."""

    return f"{value:.8g}"


def insert_rule(text: str, scope: str, factor: float) -> str:
    start = text.find("&EmissionScalingRules")
    if start < 0:
        raise ValueError("baseline namelist has no &EmissionScalingRules section")

    close = text.find("\n/", start)
    if close < 0:
        raise ValueError("could not find the end of &EmissionScalingRules")

    section = text[start:close]
    if not re.search(r"ChemFamilyName|NOX", text):
        raise ValueError("baseline namelist does not define a NOX chemical family")
    # The generic baseline file leaves the region/family definitions
    # commented out, while the lead-time control files activate them.  Add
    # the definitions needed by a regional NOx rule.
    if re.search(r"(?m)^&ChemicalFamilies\b", text) is None:
        chemical_marker = text.find("!&ChemicalFamilies")
        if chemical_marker < 0:
            raise ValueError("could not place the NOX chemical family")
        chemical_block = (
            "&ChemicalFamilies\n"
            " NChemFamilies         = 1\n"
            " ChemFamilyName(1)     = 'NOX'\n"
            " ChemFamilyNum(1)      = 2\n"
            " ChemFamilyMembers(1,:)= 'NO','NO2'\n"
            "/\n\n"
        )
        text = text[:chemical_marker] + chemical_block + text[chemical_marker:]

    # The generic baseline file leaves StreamFamilies commented out, while
    # the lead-time control files activate ALL_MM for the gridded area stream.
    # Add the same active definition when it is absent so that the NOx rule
    # does not accidentally scale point or inline emissions.
    if "'ALL_MM'" not in text:
        stream_block = (
            "&StreamFamilies\n"
            " NStreamFamilies         = 1\n"
            " StreamFamilyName(1)     = 'ALL_MM'\n"
            " StreamFamilyNum(1)      = 1\n"
            " StreamFamilyMembers(1,:)= 'GRIDDED_AV'\n"
            "/\n\n"
        )
        stream_marker = text.find("!&StreamFamilies")
        if stream_marker >= 0:
            text = text[:stream_marker] + stream_block + text[stream_marker:]
        else:
            registry_marker = text.find("&RegionsRegistry")
            if registry_marker < 0:
                raise ValueError("could not place the ALL_MM stream family")
            text = text[:registry_marker] + stream_block + text[registry_marker:]

    registry_start = text.find("&RegionsRegistry")
    registry_close = text.find("\n/", registry_start)
    if registry_start < 0 or registry_close < 0:
        raise ValueError("baseline namelist has no &RegionsRegistry section")
    if "'D3-PRD'" not in text[registry_start:registry_close]:
        text = text[:registry_close] + "\n" + REGION_LINES + text[registry_close:]
    # EVERYWHERE is CMAQ's built-in whole-domain region and therefore does
    # not need a RegionsRegistry entry.  All other scopes must be present in
    # the active registry above.
    if scope != "EVERYWHERE" and f"'{scope}'" not in text:
        raise ValueError(f"scope {scope!r} is not registered in the baseline namelist")

    marker = (
        "\n   ! PR validation: regional NOx multiplier generated by "
        "generate_emissctrl.py\n"
    )
    rule = (
        f"   '{scope}', 'ALL_MM', 'ALL', 'NOX', 'GAS', "
        f"{format_factor(factor)}, 'UNIT', 'm',\n"
    )
    # The stream block may have been inserted before ``close`` was computed;
    # it is before the emission section, so the original offset remains valid.
    return text[:close] + marker + rule + text[close:]


def main() -> int:
    args = parse_args()
    scope = args.scope.strip().upper()
    if scope not in ALLOWED_SCOPES:
        raise SystemExit(
            f"unsupported scope {scope!r}; choose one of "
            f"{', '.join(sorted(ALLOWED_SCOPES))}"
        )
    if not math.isfinite(args.nox_factor) or args.nox_factor <= 0:
        raise SystemExit("--nox-factor must be a finite number greater than zero")
    if not args.base.is_file():
        raise SystemExit(f"baseline namelist not found: {args.base}")

    output = args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    baseline = args.base.read_text(encoding="utf-8")
    rendered = insert_rule(baseline, scope, args.nox_factor)
    output.write_text(rendered, encoding="utf-8")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
